def linear_interp(x1,x2,y1,y2,x):
    k = 1.0 * (y2 - y1) / (x2 - x1)
    return k * (x - x1) + y1

def get_percent(inputAge, inputHeight, sex):

    if (inputAge < 0 or inputAge > 18):
        return 0

    percentList = [3, 10, 25, 50, 75, 90, 97]
    ageList=[]
    heightList = []

    if sex == 2:
        data = arrGril
    if sex == 1:
        data = arrBoy

    for ageStr in data:
        age = float(ageStr)
        ageList.append(age)
        l = []
        for heightStr in data[ageStr]:
            if heightStr=='0':
                continue
            height = float(heightStr)
            l.append(height)
        heightList.append(l)

    for i in range(0, len(ageList)):
        if (inputAge >= ageList[i] and inputAge <= ageList[i + 1]):
            break

    if (inputHeight < heightList[i][0]):
        j1 = 0
    else:
        for j1 in range(0, len(heightList[i])-1):
            if (inputHeight >= heightList[i][j1] and inputHeight <= heightList[i][j1 + 1]):
                break
    
    if (inputHeight < heightList[i + 1][0]):
        j2 = 0
    else:
        for j2 in range(0, len(heightList[i + 1])-1):
            if (inputHeight >= heightList[i + 1][j2] and inputHeight <= heightList[i + 1][j2 + 1]):
                break

    x = inputAge
    y = inputHeight
    x1 = ageList[i]
    x2 = ageList[i + 1]
    y11 = heightList[i][j1]
    y12 = heightList[i][j1 + 1]
    y21 = heightList[i + 1][j2]
    y22 = heightList[i + 1][j2 + 1]
    h1 = linear_interp(y11, y12, percentList[j1], percentList[j1 + 1], y)
    h2 = linear_interp(y21, y22, percentList[j2], percentList[j2 + 1], y)
    h = linear_interp(x1, x2, h1, h2, x)
    if (h > 100):
        h = 100
    if (h < 0):
        h = 0
    return h

